/**
 * Sip & Scoop — PostgreSQL schema (Supabase), defined with Drizzle ORM.
 * Change this file → `npm run db:generate` (writes SQL to drizzle/) → `npm run db:migrate`.
 */
import { sql } from "drizzle-orm";
import { boolean, index, integer, jsonb, pgEnum, pgTable, serial, text, timestamp, uniqueIndex } from "drizzle-orm/pg-core";
import { createId } from "./id";

const id = () => text("id").primaryKey().$defaultFn(createId);
const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();
const updatedAt = () =>
  timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());

// ───────────────────────── Menu ─────────────────────────

export const categories = pgTable(
  "categories",
  {
    id: id(),
    slug: text("slug").notNull(),
    name: text("name").notNull(),
    tagline: text("tagline").notNull().default(""),
    color: text("color").notNull(),
    art: text("art").notNull(),
    sortOrder: integer("sort_order").notNull().default(0),
  },
  (t) => [uniqueIndex("categories_slug_key").on(t.slug), index("categories_sort_idx").on(t.sortOrder)],
);

export const products = pgTable(
  "products",
  {
    id: id(),
    slug: text("slug").notNull(),
    name: text("name").notNull(),
    description: text("description").notNull().default(""),
    price: integer("price").notNull(), // whole PKR
    image: text("image"),
    art: text("art").notNull(),
    tint: text("tint").notNull(),
    tags: text("tags").array().notNull().default(sql`'{}'::text[]`),
    options: jsonb("options").notNull().default(sql`'[]'::jsonb`), // OptionGroup[]
    available: boolean("available").notNull().default(true),
    featured: boolean("featured").notNull().default(false),
    sortOrder: integer("sort_order").notNull().default(0),
    categoryId: text("category_id")
      .notNull()
      .references(() => categories.id, { onDelete: "restrict" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index("products_category_sort_idx").on(t.categoryId, t.sortOrder), index("products_available_idx").on(t.available)],
);

export const features = pgTable("features", {
  id: id(),
  title: text("title").notNull(),
  description: text("description").notNull().default(""),
  icon: text("icon").notNull(),
  active: boolean("active").notNull().default(true),
  sortOrder: integer("sort_order").notNull().default(0),
});

// ───────────────────────── Admin team ─────────────────────────

export const roleEnum = pgEnum("role", ["owner", "admin", "editor"]);

export const adminUsers = pgTable(
  "admin_users",
  {
    id: id(),
    name: text("name").notNull(),
    email: text("email").notNull(),
    role: roleEnum("role").notNull(),
    passwordHash: text("password_hash").notNull(),
    active: boolean("active").notNull().default(true),
    /** bumped on password change / role change / deactivation → old login cookies stop working */
    sessionVersion: integer("session_version").notNull().default(1),
    createdAt: createdAt(),
    lastLoginAt: timestamp("last_login_at", { withTimezone: true }),
  },
  (t) => [uniqueIndex("admin_users_email_key").on(t.email)],
);

// ───────────────────────── Orders ─────────────────────────

export const orderStatusEnum = pgEnum("order_status", ["new", "confirmed", "preparing", "on-the-way", "completed", "cancelled"]);

export const orders = pgTable(
  "orders",
  {
    id: id(),
    /** public order code is "SS-" + (1000 + number) — generated by the database, never clashes */
    number: serial("number").notNull(),
    type: text("type").notNull(), // delivery | pickup
    customerName: text("customer_name").notNull(),
    customerPhone: text("customer_phone").notNull(), // normalised: 03XXXXXXXXX
    customerEmail: text("customer_email").notNull().default(""),
    address: text("address").notNull().default(""),
    area: text("area").notNull().default(""),
    notes: text("notes").notNull().default(""),
    subtotal: integer("subtotal").notNull(),
    deliveryFee: integer("delivery_fee").notNull(),
    total: integer("total").notNull(),
    payment: text("payment").notNull(), // cod | jazzcash | easypaisa | card (all paid on delivery / pickup)
    status: orderStatusEnum("status").notNull().default("new"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    preparingAt: timestamp("preparing_at", { withTimezone: true }),
    dispatchedAt: timestamp("dispatched_at", { withTimezone: true }),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    confirmedAt: timestamp("confirmed_at", { withTimezone: true }), // when staff phoned the customer to confirm
    cancelledAt: timestamp("cancelled_at", { withTimezone: true }),
  },
  (t) => [
    uniqueIndex("orders_number_key").on(t.number),
    index("orders_created_idx").on(t.createdAt),
    index("orders_status_idx").on(t.status),
    index("orders_phone_idx").on(t.customerPhone),
  ],
);

export const orderItems = pgTable(
  "order_items",
  {
    id: id(),
    orderId: text("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "cascade" }),
    productId: text("product_id").references(() => products.id, { onDelete: "set null" }),
    name: text("name").notNull(), // snapshot at order time
    unitPrice: integer("unit_price").notNull(),
    qty: integer("qty").notNull(),
    options: text("options").notNull().default(""),
  },
  (t) => [index("order_items_order_idx").on(t.orderId)],
);

// ───────────────────────── Inbox ─────────────────────────

export const messages = pgTable(
  "messages",
  {
    id: id(),
    name: text("name").notNull(),
    email: text("email").notNull(),
    phone: text("phone").notNull().default(""),
    subject: text("subject").notNull().default(""),
    message: text("message").notNull(),
    read: boolean("read").notNull().default(false),
    createdAt: createdAt(),
  },
  (t) => [index("messages_created_idx").on(t.createdAt)],
);

export const subscribers = pgTable(
  "subscribers",
  {
    id: id(),
    email: text("email").notNull(),
    unsubscribeToken: text("unsubscribe_token").notNull(),
    active: boolean("active").notNull().default(true),
    createdAt: createdAt(),
    unsubscribedAt: timestamp("unsubscribed_at", { withTimezone: true }),
  },
  (t) => [uniqueIndex("subscribers_email_key").on(t.email), uniqueIndex("subscribers_token_key").on(t.unsubscribeToken)],
);

// ───────────────────────── AI assistant ─────────────────────────

export const chatConversations = pgTable(
  "chat_conversations",
  {
    id: id(),
    ipHash: text("ip_hash").notNull().default(""), // salted hash, never the raw IP
    userAgent: text("user_agent").notNull().default(""),
    messageCount: integer("message_count").notNull().default(0),
    inputTokens: integer("input_tokens").notNull().default(0),
    outputTokens: integer("output_tokens").notNull().default(0),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index("chat_conversations_updated_idx").on(t.updatedAt)],
);

export const chatMessages = pgTable(
  "chat_messages",
  {
    id: id(),
    conversationId: text("conversation_id")
      .notNull()
      .references(() => chatConversations.id, { onDelete: "cascade" }),
    role: text("role").notNull(), // user | assistant
    content: text("content").notNull(),
    source: text("source").notNull().default(""), // ai | local | error
    model: text("model").notNull().default(""),
    toolCalls: text("tool_calls").array().notNull().default(sql`'{}'::text[]`),
    inputTokens: integer("input_tokens").notNull().default(0),
    outputTokens: integer("output_tokens").notNull().default(0),
    createdAt: createdAt(),
  },
  (t) => [index("chat_messages_conversation_idx").on(t.conversationId, t.createdAt), index("chat_messages_created_idx").on(t.createdAt)],
);

/** Table bookings, catering / event / cake enquiries and call-back requests (mostly captured by the AI assistant). */
export const enquiries = pgTable(
  "enquiries",
  {
    id: id(),
    type: text("type").notNull(), // table | catering | event | cake | callback | other
    name: text("name").notNull(),
    phone: text("phone").notNull(),
    email: text("email").notNull().default(""),
    date: text("date").notNull().default(""), // as told by the customer
    time: text("time").notNull().default(""),
    guests: integer("guests"),
    details: text("details").notNull().default(""),
    status: text("status").notNull().default("new"), // new | contacted | confirmed | closed
    source: text("source").notNull().default("chat"),
    conversationId: text("conversation_id").references(() => chatConversations.id, { onDelete: "set null" }),
    createdAt: createdAt(),
  },
  (t) => [index("enquiries_created_idx").on(t.createdAt), index("enquiries_status_idx").on(t.status)],
);

// ───────────────────────── System ─────────────────────────

export const settings = pgTable("settings", {
  id: integer("id").primaryKey().default(1),
  data: jsonb("data").notNull(),
  updatedAt: updatedAt(),
});

/** Fixed-window rate-limit counters — shared by every serverless instance. */
export const rateLimits = pgTable(
  "rate_limits",
  {
    key: text("key").primaryKey(),
    count: integer("count").notNull().default(0),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
  },
  (t) => [index("rate_limits_expires_idx").on(t.expiresAt)],
);
